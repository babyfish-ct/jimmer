public class LogicalDeletedSaveTest extends AbstractMutationTest {

    enum Route {
        INSERT, UPDATE, UPSERT, FALLBACK
    }

    @BeforeAll
    static void createTable() {
        jdbc(null, false, LogicalDeletedSaveTest::createTable);
    }

    private static void createTable(Connection con) throws SQLException {
        try (Statement stmt = con.createStatement()) {
            stmt.execute("create table if not exists LIFECYCLE_ITEM(" +
                    "ID bigint generated by default as identity(start with 100) primary key, CODE varchar(40) not null, " +
                    "NAME varchar(40) not null, STATUS varchar(20) not null, unique(CODE, STATUS))");
        }
    }

    @ParameterizedTest
    @EnumSource(Route.class)
    void explicitLiveStatus(Route route) {
        jdbc(con -> {
            seed(con, NEW);
            SimpleSaveResult<LifecycleItem> result = save(con, route, RUNNING);
            assertEquals(RUNNING, status(con, route == Route.INSERT ? 2 : 1));
            assertEquals(RUNNING, result.getModifiedEntity().status());
            assertEquals(1, result.getTotalAffectedRowCount());
            assertEquals(route == Route.FALLBACK ? 2 : 1, getExecutions().size());
            assertTrue(getExecutions().get(getExecutions().size() - 1).getVariables(0).contains("RUNNING"));
        });
    }

    @ParameterizedTest
    @EnumSource(Route.class)
    void unloadedStatus(Route route) {
        jdbc(con -> {
            seed(con, RUNNING);
            SimpleSaveResult<LifecycleItem> result = save(con, route, null);
            assertEquals(route == Route.INSERT ? NEW : RUNNING, status(con, route == Route.INSERT ? 2 : 1));
            if (ImmutableObjects.isLoaded(result.getModifiedEntity(), LifecycleItemProps.STATUS)) {
                assertEquals(route == Route.INSERT ? NEW : RUNNING, result.getModifiedEntity().status());
            }
            assertEquals(1, result.getTotalAffectedRowCount());
            assertEquals(route == Route.FALLBACK ? 2 : 1, getExecutions().size());
        });
    }

    @ParameterizedTest
    @EnumSource(Route.class)
    void deletedInputIsRejected(Route route) {
        jdbc(con -> {
            seed(con, NEW);
            IllegalArgumentException ex = assertThrows(IllegalArgumentException.class, () -> save(con, route, DELETED));
            assertTrue(ex.getMessage().contains("status"));
            assertTrue(ex.getMessage().contains("delete"));
            assertTrue(getExecutions().isEmpty());
            assertEquals(NEW, status(con, 1));
        });
    }

    private SimpleSaveResult<LifecycleItem> save(Connection con, Route route, LifecycleItem.Status status) {
        JSqlClient client = client(route);
        LifecycleItem input = LifecycleItemDraft.$.produce(draft -> {
            draft.setId(route == Route.INSERT ? 2L : 1L).setCode("item").setName("changed");
            if (status != null) {
                draft.setStatus(status);
            }
        });
        return client.getEntities().saveCommand(input)
                .setMode(route == Route.INSERT ? SaveMode.INSERT_ONLY : route == Route.UPDATE ? SaveMode.UPDATE_ONLY : SaveMode.UPSERT)
                .execute(con);
    }

    private JSqlClient client(Route route) {
        return getSqlClient(builder -> {
            if (route == Route.FALLBACK) {
                builder.setDialect(new H2Dialect() {
                    @Override
                    public boolean isUpsertSupported() {
                        return false;
                    }
                });
            }
        });
    }

    @ParameterizedTest
    @EnumSource(value = Route.class, names = {"UPSERT", "FALLBACK"})
    void keyIncludesLiveStatus(Route route) {
        jdbc(con -> {
            seed(con, NEW);
            try (Statement stmt = con.createStatement()) {
                stmt.executeUpdate("insert into LIFECYCLE_ITEM values(2, 'original', 'running', 'RUNNING')");
            }
            JSqlClient client = client(route);
            List<LifecycleItem> input = Arrays.asList(
                    LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("new").setStatus(NEW)),
                    LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("run").setStatus(RUNNING))
            );
            BatchSaveResult<LifecycleItem> result = client.getEntities().saveEntitiesCommand(input).execute(con);
            assertEquals(2, result.getTotalAffectedRowCount());
            assertEquals(1L, result.getItems().get(0).getModifiedEntity().id());
            assertEquals(2L, result.getItems().get(1).getModifiedEntity().id());
            assertEquals(NEW, status(con, 1));
            assertEquals(RUNNING, status(con, 2));
            assertEquals(route == Route.FALLBACK ? 2 : 1, getExecutions().size());
            assertEquals(2, getExecutions().get(getExecutions().size() - 1).getBatchCount());
            clearExecutions();
            LifecycleItem withoutStatus = LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("default"));
            assertEquals(1L, client.getEntities().saveCommand(withoutStatus).execute(con).getModifiedEntity().id());
            assertEquals(RUNNING, status(con, 2));
        });
    }

    @ParameterizedTest
    @EnumSource(value = Route.class, names = {"UPSERT", "FALLBACK"})
    void keyDoesNotMatchAnotherLiveStatus(Route route) {
        jdbc(con -> {
            seed(con, NEW);
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("run").setStatus(RUNNING));
            LifecycleItem saved = client(route).getEntities().saveCommand(input).execute(con).getModifiedEntity();
            assertNotEquals(1L, saved.id());
            assertEquals(RUNNING, status(con, saved.id()));
            assertEquals(NEW, status(con, 1));
            assertEquals(route == Route.FALLBACK ? 2 : 1, getExecutions().size());
        });
    }

    @ParameterizedTest
    @EnumSource(value = Route.class, names = {"UPDATE", "UPSERT", "FALLBACK"})
    void returningReadsUnloadedStatus(Route route) {
        jdbc(con -> {
            seed(con, RUNNING);
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setId(1).setCode("original").setName("changed"));
            LifecycleItem saved = client(route).getEntities().saveCommand(input)
                    .setMode(route == Route.UPDATE ? SaveMode.UPDATE_ONLY : SaveMode.UPSERT)
                    .setSaveReturningEnabled().execute(con, LifecycleItemFetcher.$.allScalarFields().status()).getModifiedEntity();
            assertEquals(RUNNING, saved.status());
            assertEquals(RUNNING, status(con, 1));
        });
    }

    @Test
    @SuppressWarnings("deprecation")
    void interceptorAndEventsUseTheSavedStatus() {
        jdbc(con -> {
            seed(con, NEW);
            List<EntityEvent<LifecycleItem>> events = new ArrayList<>();
            JSqlClient client = getSqlClient(b -> b.setTriggerType(TriggerType.TRANSACTION_ONLY)
                    .addDraftInterceptor(new DraftInterceptor<LifecycleItem, LifecycleItemDraft>() {
                        @Override
                        public void beforeSave(@NotNull LifecycleItemDraft draft, @Nullable LifecycleItem original) {
                            draft.setStatus(RUNNING);
                        }
                    }));
            client.getTriggers(true).addEntityListener(LifecycleItem.class, events::add);
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setId(1).setCode("original").setName("changed"));
            assertEquals(RUNNING, client.getEntities().saveCommand(input).execute(con).getModifiedEntity().status());
            assertEquals(RUNNING, status(con, 1));
            assertEquals(1, events.size());
            assertNotNull(events.get(0).getOldEntity());
            assertNotNull(events.get(0).getNewEntity());
            assertEquals(NEW, events.get(0).getOldEntity().status());
            assertEquals(RUNNING, events.get(0).getNewEntity().status());
            assertEquals(2, getExecutions().size());
        });
    }

    @Test
    void callbacksCannotWriteDeletedValues() {
        jdbc(con -> {
            seed(con, NEW);
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setId(1).setCode("original").setName("changed"));
            JSqlClient preprocessing = getSqlClient(b -> b.addDraftPreProcessor(new DraftPreProcessor<LifecycleItemDraft>() {
                @Override
                public void beforeSave(@NotNull LifecycleItemDraft draft) {
                    draft.setStatus(DELETED);
                }
            }));
            assertThrows(IllegalArgumentException.class, () -> preprocessing.getEntities().saveCommand(input).execute(con));
            assertTrue(getExecutions().isEmpty());
            JSqlClient intercepting = getSqlClient(b -> b.addDraftInterceptor(new DraftInterceptor<LifecycleItem, LifecycleItemDraft>() {
                @Override
                public void beforeSave(@NotNull LifecycleItemDraft draft, @Nullable LifecycleItem original) {
                    draft.setStatus(DELETED);
                }
            }));
            assertThrows(IllegalArgumentException.class, () -> intercepting.getEntities().saveCommand(input).execute(con));
            assertEquals(1, getExecutions().size());
            assertEquals(NEW, status(con, 1));
        });
    }

    @Test
    void booleanDeletedInputIsRejected() {
        jdbc(con -> {
            assertThrows(IllegalArgumentException.class, () -> getSqlClient().getEntities().saveCommand(
                    BoolKeyFileDraft.$.produce(d -> d.setId(1).setName("changed").setDeleted(true))
            ).setMode(SaveMode.UPDATE_ONLY).execute(con));
            assertTrue(getExecutions().isEmpty());
        });
    }

    @ParameterizedTest
    @EnumSource(value = Route.class, names = {"UPSERT", "FALLBACK"})
    void upsertInsertsDefaultOnlyWhenNew(Route route) {
        jdbc(con -> {
            seed(con, DELETED);
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setId(2).setCode("new").setName("created"));
            LifecycleItem saved = client(route).getEntities().saveCommand(input)
                    .setSaveReturningEnabled().execute(con, LifecycleItemFetcher.$.status()).getModifiedEntity();
            assertEquals(NEW, status(con, 2));
            assertEquals(NEW, saved.status());
            assertEquals(DELETED, status(con, 1));
        });
    }

    @Test
    void unloadedStatusDoesNotRestoreDeletedRow() {
        jdbc(con -> {
            seed(con, DELETED);
            save(con, Route.UPSERT, null);
            assertEquals(DELETED, status(con, 1));
            assertEquals(1, getExecutions().size());
        });
    }

    @Test
    void deleteCommandStillDeletesLiveStatus() {
        jdbc(con -> {
            seed(con, RUNNING);
            getSqlClient().getEntities().deleteCommand(LifecycleItem.class, 1L).execute(con);
            assertEquals(DELETED, status(con, 1));
        });
    }

    @Test
    void updateByKeyWithReturningMatchesStatus() {
        jdbc(con -> {
            seed(con, NEW);
            try (Statement stmt = con.createStatement()) {
                stmt.executeUpdate("insert into LIFECYCLE_ITEM values(2, 'original', 'running', 'RUNNING')");
            }
            LifecycleItem input = LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("changed").setStatus(RUNNING));
            SimpleSaveResult<LifecycleItem> result = getSqlClient().getEntities().saveCommand(input)
                    .setMode(SaveMode.UPDATE_ONLY).setSaveReturningEnabled()
                    .execute(con, LifecycleItemFetcher.$.allScalarFields().status());
            assertEquals(1, result.getTotalAffectedRowCount());
            assertEquals(2L, result.getModifiedEntity().id());
            assertEquals(NEW, status(con, 1));
            assertEquals(RUNNING, status(con, 2));
        });
    }

    @Test
    void postgresNativeUpsert() {
        NativeDatabases.assumeNativeDatabase();
        jdbc(NativeDatabases.POSTGRES_DATA_SOURCE, true, con -> {
            createTable(con);
            seed(con, NEW);
            JSqlClient client = getSqlClient(b -> b.setDialect(new PostgresDialect()));
            LifecycleItem running = LifecycleItemDraft.$.produce(d ->
                    d.setId(1).setCode("original").setName("changed").setStatus(RUNNING));
            assertEquals(RUNNING, client.getEntities().saveCommand(running).execute(con).getModifiedEntity().status());
            assertEquals(RUNNING, status(con, 1));
            assertEquals(1, getExecutions().size());
            assertTrue(getExecutions().get(0).getVariables(0).contains("RUNNING"));
            clearExecutions();
            LifecycleItem unloaded = LifecycleItemDraft.$.produce(d -> d.setId(1).setCode("original").setName("again"));
            LifecycleItem saved = client.getEntities().saveCommand(unloaded).setSaveReturningEnabled()
                    .execute(con, LifecycleItemFetcher.$.status()).getModifiedEntity();
            assertEquals(RUNNING, saved.status());
            assertEquals(RUNNING, status(con, 1));
            assertEquals(1, getExecutions().size());
            clearExecutions();
            LifecycleItem byKey = LifecycleItemDraft.$.produce(d -> d.setCode("original").setName("new-state").setStatus(NEW));
            LifecycleItem created = client.getEntities().saveCommand(byKey).execute(con).getModifiedEntity();
            assertNotEquals(1L, created.id());
            assertEquals(NEW, status(con, created.id()));
            assertEquals(RUNNING, status(con, 1));
            assertEquals(1, getExecutions().size());
        });
    }

    private static void seed(Connection con, LifecycleItem.Status status) throws SQLException {
        try (Statement stmt = con.createStatement()) {
            stmt.executeUpdate("delete from LIFECYCLE_ITEM");
            stmt.executeUpdate("insert into LIFECYCLE_ITEM(ID, CODE, NAME, STATUS) values(1, 'original', 'old', '" + status + "')");
        }
    }

    private static LifecycleItem.Status status(Connection con, long id) throws SQLException {
        try (Statement stmt = con.createStatement();
             ResultSet rs = stmt.executeQuery("select STATUS from LIFECYCLE_ITEM where ID = " + id)) {
            assertTrue(rs.next());
            return LifecycleItem.Status.valueOf(rs.getString(1));
        }
    }
}
